"""Domain models for discrete events, network packets, and execution reports."""

from dataclasses import dataclass
from enum import IntEnum
from typing import Any


class Side(IntEnum):
    """Order side."""
    BID = 1
    ASK = -1


class PacketType(IntEnum):
    """Network packet classification."""
    NEW_ORDER = 1
    CANCEL_ORDER = 2
    ORDER_ACK = 3
    ORDER_FILL = 4
    ORDER_CANCELLED = 5
    ORDER_REJECTED = 6


class OrderStatus(IntEnum):
    """Order lifecycle status."""
    IN_FLIGHT = 1
    ACCEPTED = 2
    FILLED = 3
    CANCELLED = 4
    REJECTED = 5


@dataclass(slots=True)
class OrderIntent:
    """Trading instruction generated by client strategy."""
    client_order_id: int
    side: Side
    price: float
    quantity: float
    client_timestamp_ns: int


@dataclass(slots=True)
class ExecutionReport:
    """Downstream confirmation message sent by exchange gateway."""
    client_order_id: int
    exchange_order_id: int
    status: OrderStatus
    fill_price: float
    fill_quantity: float
    exchange_timestamp_ns: int
    reason: str = ""


@dataclass(slots=True, order=True)
class DiscreteEvent:
    """Event wrapper scheduled in the simulation heap."""
    timestamp_ns: int
    priority: int
    event_type: PacketType
    payload: Any


@dataclass(slots=True)
class LatencyProfile:
    """Configuration for physical link wire transit and kernel jitter."""
    base_wire_delay_ns: int
    jitter_mu_ns: float
    jitter_sigma_ns: float
